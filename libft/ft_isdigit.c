#include "libft.h"

int	ft_isdigit(int c)
{
	if (c >= '0' && c <= '9')
		return (c);
	return (0);
}
 int main()
{
	printf("%d\n", ft_isdigit(50));
	printf("%d\n", isdigit(50));
	return (0);
}
