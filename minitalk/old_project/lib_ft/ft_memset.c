#include "libft.h"

void	*ft_memset(void *ptr, int x, size_t n)
{
	unsigned char	*c;

	c = (unsigned char *)ptr;
	while (n > 0)
	{
		c[n - 1] = x;
		n--;
	}
	return (ptr);
}
